declare(strict_types=1);

namespace Vivarium\Test\Assertion\String;

use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\TestWith;
use PHPUnit\Framework\TestCase;
use Vivarium\Assertion\Assertion;
use Vivarium\Assertion\Exception\AssertionFailed;
use Vivarium\Assertion\String\EndsWith;

use function preg_quote;

#[CoversClass(EndsWith::class)]
final class EndsWithTest extends TestCase
{
    /** @param Assertion<mixed> $assertion */
    #[DataProvider('provideValues')]
    public function testCheck(Assertion $assertion, mixed $value, string|null $message): void
    {
        self::assertSame($message === null, $assertion->check($value));
    }

    /** @param Assertion<mixed> $assertion */
    #[DataProvider('provideValues')]
    public function testAssert(Assertion $assertion, mixed $value, string|null $message): void
    {
        if ($message === null) {
            $this->expectNotToPerformAssertions();
        }

        if ($message !== null) {
            $this->expectException(AssertionFailed::class);
            $this->expectExceptionMessageMatches('/^' . preg_quote($message, '/') . '$/');
        }

        $assertion->assert($value);
    }

    #[TestWith(['Foo.phpx', 'Custom string "Foo.phpx".'])]
    public function testAssertWithCustomMessage(mixed $value, string $message): void
    {
        $this->expectException(AssertionFailed::class);
        $this->expectExceptionMessageMatches('/^' . preg_quote($message, '/') . '$/');

        (new EndsWith('.php'))->assert($value, 'Custom {value}.');
    }

    /** @return array<string, array{Assertion<mixed>, mixed, string|null}> */
    public static function provideValues(): array
    {
        $assertion = new EndsWith('.php');

        return [
            'accepts Foo.php' => [$assertion, 'Foo.php', null],
            'accepts .php' => [$assertion, '.php', null],
            'multibyte' => [new EndsWith('é'), 'café', null],
            'empty needle' => [new EndsWith(''), 'anything', null],
            'rejects Foo.phpx' => [$assertion, 'Foo.phpx', 'Expected value to end with ".php". Got string "Foo.phpx".'],
            'int' => [$assertion, 1, 'Expected value to be string. Got int 1.'],
        ];
    }
}
